const fs = require('node:fs');
const path = require('node:path');
const { withDangerousMod, withAndroidManifest, AndroidConfig } = require('expo/config-plugins');

// Lets Firefly III be reached over HTTPS with a certificate from a private CA — the homelab case:
// a self-hoster running their own CA, or a router/NAS issuing its own certs. Android stopped
// trusting user-installed CAs for app traffic in API 24; an app has to opt in, and there is no way
// to do it from JS or from expo-build-properties (checked: it has no networkSecurityConfig option).
//
// What this does NOT do is disable certificate verification. A cert still has to chain to something
// the *device owner* chose to trust (Settings → Security → Encryption & credentials → Install a
// certificate → CA certificate). A self-signed cert that is not installed on the device is still
// refused, which is the point: "trust anything" would make every mmyway install one bad Wi-Fi away
// from a silent man-in-the-middle on the user's whole ledger.
//
// `cleartextTrafficPermitted="true"` is not an extra: once a network security config exists it
// overrides `android:usesCleartextTraffic` in the manifest (API 24+), so leaving it out would
// silently undo the plain-http support that app.config.js's expo-build-properties block sets up
// for LAN IPs and tailnet names.

const RES_FILE = 'network_security_config.xml';

const CONFIG_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withUserCaTrust.js — edit the plugin, not this file. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="true">
        <trust-anchors>
            <certificates src="system" />
            <!-- CAs the device owner installed themselves. Without this line, an HTTPS Firefly
                 III behind a private CA fails to connect with no usable error. -->
            <certificates src="user" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;

function withNetworkSecurityConfigFile(config) {
  return withDangerousMod(config, [
    'android',
    (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, RES_FILE), CONFIG_XML);
      return config;
    },
  ]);
}

/** Points `<application>` at the resource above. Separated out so the test can run it alone. */
function setNetworkSecurityConfigAttribute(androidManifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
  return androidManifest;
}

function withNetworkSecurityConfigManifest(config) {
  return withAndroidManifest(config, (config) => {
    setNetworkSecurityConfigAttribute(config.modResults);
    return config;
  });
}

module.exports = function withUserCaTrust(config) {
  return withNetworkSecurityConfigManifest(withNetworkSecurityConfigFile(config));
};

// For plugins/withUserCaTrust.test.js — the two things that silently break connectivity if wrong.
module.exports.NETWORK_SECURITY_CONFIG_XML = CONFIG_XML;
module.exports.setNetworkSecurityConfigAttribute = setNetworkSecurityConfigAttribute;
